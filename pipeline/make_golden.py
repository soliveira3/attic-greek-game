"""Copy the generated tables of the golden lemmas into data/golden/<lemma>.json.

Usage: python make_golden.py

Golden files start with "verified": false. Only the user sets it to true, after checking every
cell against Smyth or a textbook; tests then require the generated data to match the file exactly.
A verified file is never overwritten. data/golden/REVIEW.md shows each table as a grid to make
the check quick.
"""
import csv
import json
import sys
from pathlib import Path

from normalize import nfc

ROOT = Path(__file__).resolve().parent.parent
PARADIGMS = ROOT / "data" / "paradigms"
GOLDEN = ROOT / "data" / "golden"

NOTE = (
    "Check every cell against Smyth's Greek Grammar or your textbook. Do not edit forms: if a cell "
    "is wrong, report it so it can be excluded upstream. When every cell is right, set verified to true."
)
CASES = ["nom", "gen", "dat", "acc", "voc"]
NUMBERS = [("sg", "singular"), ("pl", "plural"), ("du", "dual")]
GENDERS = ["m", "f", "n"]
TENSES = ["pres", "impf", "fut", "aor", "perf"]
VOICES = {"act": "active", "mid": "middle", "pass": "passive", "mp": "middle/passive"}
TENSE_NAMES = {"pres": "present", "impf": "imperfect", "fut": "future", "aor": "aorist", "perf": "perfect"}


def golden_doc(lemma: dict) -> dict:
    return {
        "lemma": lemma["lemma"],
        "pos": lemma["pos"],
        "class": lemma["class"],
        "verified": False,
        "verifiedBy": "",
        "verifiedOn": "",
        "note": NOTE,
        "cells": {c["key"]: c["forms"] for c in lemma["cells"]},
    }


def render_golden(doc: dict) -> str:
    dump = lambda v: json.dumps(v, ensure_ascii=False)  # noqa: E731
    head = [f"  {dump(k)}: {dump(v)}," for k, v in doc.items() if k != "cells"]
    cells = [f"    {dump(k)}: {dump(v)}" for k, v in doc["cells"].items()]
    return "{\n" + "\n".join(head) + '\n  "cells": {\n' + ",\n".join(cells) + "\n  }\n}\n"


def write_golden(directory: Path, lemmas: list[dict]) -> tuple[list[str], list[str]]:
    """Write unverified golden files; return (written, kept-because-verified)."""
    written, kept = [], []
    directory.mkdir(parents=True, exist_ok=True)
    for lemma in lemmas:
        path = directory / f"{lemma['lemma']}.json"
        if path.exists() and json.loads(path.read_text(encoding="utf-8")).get("verified") is True:
            kept.append(lemma["lemma"])
            continue
        path.write_text(render_golden(golden_doc(lemma)), encoding="utf-8")
        written.append(lemma["lemma"])
    return written, kept


def _cell(cells: dict, key: str) -> str:
    return " / ".join(cells.get(key, []))


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows if any(r[1:])]
    return out


def render_review(docs: list[dict]) -> str:
    out = [
        "# Golden paradigms: review sheet",
        "",
        "Generated by `pipeline/make_golden.py` from `data/golden/*.json`. Check each grid against",
        "Smyth (or your textbook), then set `\"verified\": true` in that lemma's JSON file.",
        "Alternates are separated by ` / `; vowel-length marks come from Wiktionary and are optional.",
        "",
    ]
    for doc in docs:
        cells = doc["cells"]
        status = "verified" if doc["verified"] else "not verified yet"
        out += [f"## {doc['lemma']}", "", f"`{doc['class']}` · {status} · file `data/golden/{doc['lemma']}.json`", ""]
        if doc["pos"] == "noun":
            out += _table(["case", "singular", "plural", "dual"], [[c] + [_cell(cells, f"{c}.{n}") for n, _ in NUMBERS] for c in CASES])
        elif doc["pos"] in ("adj", "article"):
            for n, name in NUMBERS:
                out += [f"**{name}**", ""]
                out += _table(["case", "masc.", "fem.", "neut."], [[c] + [_cell(cells, f"{c}.{n}.{g}") for g in GENDERS] for c in CASES])
                out.append("")
        else:
            for t in TENSES:
                for v, vname in VOICES.items():
                    block = f"{t}.{v}"
                    if not any(k.startswith(block + ".") for k in cells):
                        continue
                    out += [f"**{TENSE_NAMES[t]} {vname}**", ""]
                    rows = [[p] + [_cell(cells, f"{block}.ind.{p}.{n}") for n, _ in NUMBERS] for p in ("1", "2", "3")]
                    if any(any(r[1:]) for r in rows):
                        out += _table(["person", "singular", "plural", "dual"], rows)
                    if cells.get(f"{block}.inf"):
                        out += ["", f"infinitive: {_cell(cells, f'{block}.inf')}"]
                    out.append("")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    with (GOLDEN / "LEMMAS.csv").open(encoding="utf-8", newline="") as f:
        wanted = [(nfc(r["lemma"]), r["pos"], r["class"]) for r in csv.DictReader(f)]
    generated = {
        (lem["lemma"], lem["pos"]): lem
        for name in ("nouns.json", "adjectives.json", "verbs.json")
        for lem in json.loads((PARADIGMS / name).read_text(encoding="utf-8"))["lemmas"]
    }
    lemmas, problems = [], []
    for lemma, pos, cls in wanted:
        found = generated.get((lemma, pos))
        if found is None:
            problems.append(f"{lemma} ({pos}) is not in the generated data")
        elif found["class"] != cls:
            problems.append(f"{lemma} is {found['class']}, expected {cls}")
        else:
            lemmas.append(found)
    for p in problems:
        print("problem:", p, file=sys.stderr)
    written, kept = write_golden(GOLDEN, lemmas)
    docs = [json.loads((GOLDEN / f"{lem['lemma']}.json").read_text(encoding="utf-8")) for lem in lemmas]
    (GOLDEN / "REVIEW.md").write_text(render_review(docs), encoding="utf-8")
    print(f"golden: wrote {len(written)}, kept {len(kept)} verified; review sheet data/golden/REVIEW.md")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
