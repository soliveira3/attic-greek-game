"""Draw a reproducible random sample of forms from the paradigm data for a human reviewer.

The golden models marked verified are left out (they were compared with Smyth already), and so are dual
cells (not drilled by default). Parts of speech are sampled in proportion to their number of
words; within one, a word is drawn first and then one of its cells, so verbs with many cells do
not crowd out the rest. Every form of the cell is listed, copied from data/paradigms/ unchanged.

Usage: python review_sample.py [--n 40] [--seed 1] > ../docs/REVIEW_SAMPLE.md
"""

import argparse
import json
import random
from pathlib import Path

from normalize import nfc

ROOT = Path(__file__).resolve().parent.parent
FILES = ("nouns.json", "adjectives.json", "verbs.json")
POS_ORDER = ("noun", "adj", "verb", "article")

CASES = {"nom": "nominative", "gen": "genitive", "dat": "dative", "acc": "accusative", "voc": "vocative"}
NUMBERS = {"sg": "singular", "pl": "plural", "du": "dual"}
GENDERS = {"m": "masculine", "f": "feminine", "n": "neuter"}
TENSES = {"pres": "present", "impf": "imperfect", "fut": "future", "aor": "aorist", "perf": "perfect"}
VOICES = {"act": "active", "mid": "middle", "pass": "passive"}
MOODS = {"ind": "indicative", "inf": "infinitive"}
PERSONS = {"1": "1st", "2": "2nd", "3": "3rd"}


def load_lemmas(data_dir: Path) -> list[dict]:
    out = []
    for name in FILES:
        out += json.loads((data_dir / "paradigms" / name).read_text(encoding="utf-8"))["lemmas"]
    return out


def cell_label(cell: dict) -> str:
    """The cell's features in plain English, in the order a grammar names them."""
    if "tense" in cell:
        words = [TENSES[cell["tense"]], "/".join(VOICES[v] for v in cell["voice"]), MOODS[cell["mood"]]]
        if "person" in cell:
            words += [PERSONS[cell["person"]], NUMBERS[cell["number"]]]
        return " ".join(words)
    words = [CASES[cell["case"]], NUMBERS[cell["number"]]]
    if cell.get("gender"):
        words.append(GENDERS[cell["gender"]])
    return " ".join(words)


def _golden_ids(data_dir: Path) -> set[str]:
    """Golden models marked verified (compared with Smyth already)."""
    out = set()
    for p in (data_dir / "golden").glob("*.json"):
        if json.loads(p.read_text(encoding="utf-8")).get("verified") is True:
            out.add(nfc(p.stem))
    return out


def _quotas(sizes: dict[str, int], n: int) -> dict[str, int]:
    """n split in proportion to sizes (largest remainder)."""
    total = sum(sizes.values())
    exact = {pos: n * size / total for pos, size in sizes.items()}
    out = {pos: int(x) for pos, x in exact.items()}
    for pos in sorted(exact, key=lambda p: exact[p] - out[p], reverse=True)[: n - sum(out.values())]:
        out[pos] += 1
    return out


def sample(lemmas: list[dict], n: int, seed: int, data_dir: Path = ROOT / "data") -> list[dict]:
    rng = random.Random(seed)
    golden = _golden_ids(data_dir)
    by_pos: dict[str, list[dict]] = {}
    for lem in lemmas:
        cells = [c for c in lem["cells"] if c.get("number") != "du" and c["forms"]]
        if nfc(lem["id"]) not in golden and cells:
            by_pos.setdefault(lem["pos"], []).append({**lem, "cells": cells})
    quotas = _quotas({pos: len(lems) for pos, lems in by_pos.items()}, n)
    items: list[dict] = []
    for pos in sorted(by_pos, key=lambda p: POS_ORDER.index(p) if p in POS_ORDER else len(POS_ORDER)):
        lems, taken = by_pos[pos], set()
        available = sum(len(lem["cells"]) for lem in lems)
        while len(taken) < min(quotas[pos], available):
            lem = rng.choice(lems)
            cell = rng.choice(lem["cells"])
            if (lem["id"], cell["key"]) in taken:
                continue
            taken.add((lem["id"], cell["key"]))
            items.append({
                "pos": pos, "id": lem["id"], "lemma": lem["lemma"], "gloss": lem.get("gloss", ""),
                "cell": cell["key"], "label": cell_label(cell), "forms": list(cell["forms"]),
            })
    return items


def render_markdown(items: list[dict], seed: int) -> str:
    lines = [
        "# Review sample",
        "",
        "Generated by `pipeline/review_sample.py`; do not edit (a test compares this file with the script's output).",
        "How to use it: [REVIEW_GUIDE.md](REVIEW_GUIDE.md). Where a cell has more than one accepted spelling, all are",
        "listed, separated by \" / \".",
        "",
        f"Sample of {len(items)} cells, seed {seed} (`python pipeline/review_sample.py --n {len(items)} --seed {seed}`).",
        "",
        "| # | Word | Meaning | Asked | Forms in the game | Right? |",
        "|---|---|---|---|---|---|",
    ]
    for i, item in enumerate(items, 1):
        gloss = item["gloss"].split(";")[0].replace("|", "/")
        lines.append(f"| {i} | {item['lemma']} | {gloss} | {item['label']} | {' / '.join(item['forms'])} |  |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--n", type=int, default=40)
    parser.add_argument("--seed", type=int, default=1)
    args = parser.parse_args()
    print(render_markdown(sample(load_lemmas(ROOT / "data"), args.n, args.seed), args.seed), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
